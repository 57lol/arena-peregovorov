"""Мелкий пиксельный шрифт 3×5 для надписей на картинках: FONT из room3d.py плюс недостающие буквы."""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from room3d import FONT  # noqa: E402

GLYPHS = dict(FONT)
GLYPHS.update({
    'Г': ['###', '#..', '#..', '#..', '#..'], 'И': ['#..#', '#..#', '#.##', '##.#', '#..#'],
    'Й': ['#.##', '#..#', '#.##', '##.#', '#..#'], 'У': ['#.#', '#.#', '.##', '..#', '##.'],
    'Ш': ['#.#.#', '#.#.#', '#.#.#', '#.#.#', '#####'], 'Ы': ['#...#', '#...#', '###.#', '#.#.#', '###.#'],
    'Х': ['#.#', '#.#', '.#.', '#.#', '#.#'], 'Ь': ['#..', '#..', '##.', '#.#', '##.'],
    '«': ['....', '.#.#', '#.#.', '.#.#', '....'], '»': ['....', '#.#.', '.#.#', '#.#.', '....'],
    '→': ['..#..', '...#.', '#####', '...#.', '..#..'], 'Ж': ['#.#.#', '#.#.#', '.###.', '#.#.#', '#.#.#'],
    'Ф': ['.#.', '###', '#.#', '###', '.#.'], 'Ю': ['#.##', '#.##', '####', '#.##', '#.##'], ':': ['.', '#', '.', '#', '.'],
    '!': ['#', '#', '#', '.', '#'], '₽': ['##.', '#.#', '##.', '###', '#..'],
})


def text(canvas, x, y, s, c, gap=1):
    """Надпись индексом палитры c на любом холсте с методом px."""
    for ch in s:
        g = GLYPHS[ch]
        for dy, row in enumerate(g):
            for dx, v in enumerate(row):
                if v == '#':
                    canvas.px(x + dx, y + dy, c)
        x += len(g[0]) + gap


def text_w(s, gap=1):
    return sum(len(GLYPHS[ch][0]) + gap for ch in s) - gap
