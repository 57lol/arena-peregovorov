export const mainRef = (id: string): BookRef | undefined => TECHNIQUES[id as BehaviorId]?.refs[0]

/** «Восс, «Никаких компромиссов», гл. 3». full: с названием приёма в книге. */
export function cite(ref: BookRef, opts: { title?: boolean; name?: boolean } = {}): string {
  const b = BOOKS[ref.book]
  const title = opts.title === false ? '' : `, «${shortTitle(b)}»`
  const name = opts.name ? `, «${ref.name}»` : ''
  return `${b.short}${title}, ${ref.where}${name}`
}

/** Короткое название для подписи: без подзаголовка после точки или запятой. */
export const shortTitle = (b: Book) => b.title.split(/\.\s|,\s/u)[0]

/** Подпись приёма: «— Восс, «Никаких компромиссов», гл. 3» или пустая строка, если книги нет. */
export function signature(id: string, opts: { title?: boolean; name?: boolean } = {}): string {
  const ref = mainRef(id)
  return ref ? `— ${cite(ref, opts)}` : ''
}

/** Приёмы книги в том порядке, как они идут в игре: сначала, где книга — главный источник. */
export function techniquesOf(book: BookId): { id: BehaviorId; ref: BookRef; main: boolean }[] {
  const out: { id: BehaviorId; ref: BookRef; main: boolean }[] = []
  for (const [id, t] of Object.entries(TECHNIQUES) as [BehaviorId, Technique][]) {
    const k = t.refs.findIndex((x) => x.book === book)
    if (k >= 0) out.push({ id, ref: t.refs[k], main: k === 0 })
  }
  return out.sort((a, b) => Number(b.main) - Number(a.main))
}
