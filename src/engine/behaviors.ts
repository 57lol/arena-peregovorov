/** Словарь в виде блока для промпта: определение, примеры, с чем не путать. */
export function behaviorGuide(): string {
  return BEHAVIORS.map((b) => {
    const ex = b.examples.map((e) => `«${e}»`).join(' ')
    return `- ${b.id} — ${b.title}. ${b.definition}${b.notThis ? ` Не путать: ${b.notThis}` : ''} Примеры: ${ex}`
  }).join('\n')
}
