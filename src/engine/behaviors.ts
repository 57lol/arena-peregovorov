/** Контекст хода, без которого часть индикаторов не определить. */
export interface MoveContext {
  offered?: boolean            // в реплике есть конкретное предложение (из parseOffer или блокнота)
  firstOffer?: boolean         // это первое предложение игрока за встречу
  opponentJustOffered?: boolean // прошлым ходом оппонент положил на стол своё предложение
}

// Если сработал ключ, индикаторы из значения снимаются: одна фраза — одно поведение.
const EXCLUDES: Partial<Record<BehaviorId, BehaviorId[]>> = {
  ultimatum: ['alternative', 'meso', 'package'],
  attack: ['label'],
}

// Если в ходе есть что-то из этого, встречное уже не «мгновенное».
const ENGAGES: BehaviorId[] = ['ask_interest', 'check', 'label', 'summarize', 'priority']

function quoteAround(text: string, at: number, len: number): string {
  const before = text.slice(0, at)
  const start = Math.max(before.lastIndexOf('.'), before.lastIndexOf('!'), before.lastIndexOf('?'), before.lastIndexOf('\n')) + 1
  const rest = text.slice(at + len).search(/[.!?\n]/)
  const end = rest < 0 ? text.length : at + len + rest + 1
  const q = text.slice(start, end).trim()
  return q.length > 120 ? text.slice(Math.max(start, at - 40), Math.min(end, at + len + 40)).trim() + '…' : q
}

/**
 * Разметка реплики правилами — для офлайн-режима и как страховка к LLM.
 * Каждый индикатор не больше одного раза за ход, у каждого — цитата.
 */
export function detectBehaviors(text: string, ctx: MoveContext = {}): BehaviorHit[] {
  const hits = new Map<BehaviorId, BehaviorHit>()
  for (const b of BEHAVIORS) {
    for (const m of b.markers) {
      const found = m.exec(text)
      if (found) {
        hits.set(b.id, { id: b.id, quote: quoteAround(text, found.index, found[0].length) })
        break
      }
    }
  }
  for (const [id, drop] of Object.entries(EXCLUDES) as [BehaviorId, BehaviorId[]][])
    if (hits.has(id)) for (const d of drop) hits.delete(d)

  if (ctx.offered && ctx.firstOffer && !hits.has('anchor')) hits.set('anchor', { id: 'anchor', quote: quoteAround(text, 0, 0) })
  const engaged = ENGAGES.some((id) => hits.has(id))
  if (ctx.offered && ctx.opponentJustOffered && !engaged && !hits.has('instant_counter'))
    hits.set('instant_counter', { id: 'instant_counter', quote: quoteAround(text, 0, 0) })
  if (engaged) hits.delete('instant_counter')
  return [...hits.values()]
}

// ——— профиль против эталона ———

export const MINUTES_PER_TURN = 5

export interface ProfileRow {
  id: BehaviorId
  title: string
  polarity: Polarity
  count: number
  value?: number           // в единицах эталона
  benchmark?: Benchmark
  verdict?: 'skilled' | 'between' | 'average'
}

/**
 * Профиль поведения игрока против эталона Rackham & Carlisle.
 * Честная оговорка: там считали высказывания в живой речи, у нас — письменные ходы, и один ход длиннее
 * одного высказывания. Поэтому доли у нас выходят выше, и эталон сильных — скорее нижняя планка, чем норма.
 */
export function behaviorProfile(turns: { behaviors: BehaviorHit[] }[]): ProfileRow[] {
  const n = turns.length
  const hours = (n * MINUTES_PER_TURN) / 60
  return BEHAVIORS.map((b) => {
    const count = turns.filter((t) => t.behaviors.some((h) => h.id === b.id)).length
    const row: ProfileRow = { id: b.id, title: b.title, polarity: b.polarity, count }
    const bm = b.benchmark
    if (!bm || !n) return row
    row.benchmark = bm
    if (bm.unit === 'reasons') {
      // «доводов на аргумент» из счётчика не восстановить: индикатор и есть порог. Сработал — как у средних.
      row.verdict = count ? 'average' : 'skilled'
      return row
    }
    const v = (row.value = bm.unit === 'share' ? +((count / n) * 100).toFixed(1) : +(count / hours).toFixed(1))
    const higherIsBetter = b.polarity === 'strong'
    const nearSkilled = higherIsBetter ? v >= bm.skilled : v <= bm.skilled
    const nearAverage = higherIsBetter ? v <= bm.average : v >= bm.average
    row.verdict = nearSkilled ? 'skilled' : nearAverage ? 'average' : 'between'
    return row
  })
}

/** Сколько очков по осям набрал игрок: сильные в плюс, слабые в минус. Для «паутинки» в разборе. */
export function axisScores(turns: { behaviors: BehaviorHit[] }[]): Record<Axis, number> {
  const out: Record<Axis, number> = { create: 0, claim: 0, relate: 0, process: 0 }
  for (const t of turns)
    for (const h of t.behaviors) {
      const b = behaviorById(h.id)
      if (b) out[b.axis] += b.polarity === 'strong' ? 1 : b.polarity === 'weak' ? -1 : 0
    }
  return out
}

