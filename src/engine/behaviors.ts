// Границы слова для кириллицы: \b в JS понимает только латиницу.
const L = '(?<![\\p{L}\\p{N}])'
const R = '(?![\\p{L}\\p{N}])'
const S = '[^.!?\\n]' // «в пределах одного предложения»
const re = (src: string) => new RegExp(src.replaceAll('‹', L).replaceAll('›', R).replaceAll('§', S), 'iu')
// Только в вопросе: либо в начале предложения (после «а», «скажите», обращения по имени), либо в предложении есть «?».
// Иначе «понимаю, что для вас важно…» считалось бы вопросом.
const LEAD = '(?:(?:а|и|но|так|ну|скажите|подскажите|слушайте|хорошо|ладно|понятно|окей)[,!]?\\s+)*(?:[\\p{L}-]+,\\s+)?'
const q = (src: string) => re(`(?:(?:^|[.!?\\n]\\s*)${LEAD}${src}|${src}(?=§*\\?))`)

