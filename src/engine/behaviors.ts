/** Контекст хода, без которого часть индикаторов не определить. */
export interface MoveContext {
  offered?: boolean            // в реплике есть конкретное предложение (из parseOffer или блокнота)
  firstOffer?: boolean         // это первое предложение игрока за встречу
  opponentJustOffered?: boolean // прошлым ходом оппонент положил на стол своё предложение
}

// Если сработал ключ, индикаторы из значения снимаются: одна фраза — одно поведение.
// Ультиматум и атака не бывают заодно «объявлением хода» или разменом: в «что работало» такая реплика не попадёт.
const BOOK_GOOD: BehaviorId[] = ['mirror', 'calibrated', 'accusation_audit', 'no_question', 'golden_bridge', 'i_message', 'balcony']
const EXCLUDES: Partial<Record<BehaviorId, BehaviorId[]>> = {
  ultimatum: ['alternative', 'meso', 'package', 'signpost', 'joint_frame', 'whatif', 'need_payoff', 'criteria', 'implication', 'deadline', ...BOOK_GOOD],
  attack: ['label', 'signpost', 'package', 'rapport', 'joint_frame', 'criteria', 'whatif', 'implication', 'need_payoff', ...BOOK_GOOD],
  // «решайте сейчас — вы против?» — нажим, а не вопрос под «нет»
  deadline: ['no_question', 'balcony'],
  // одна фраза — одно поведение: конкретный размен или готовые пакеты точнее «пробного варианта»
  package: ['whatif'],
  meso: ['whatif'],
}

// Если в ходе есть что-то из этого, встречное уже не «мгновенное».
export const ENGAGES: BehaviorId[] = ['ask_interest', 'check', 'label', 'summarize', 'priority', 'implication', 'need_payoff', 'mirror', 'calibrated', 'accusation_audit', 'golden_bridge']

// Одна фраза — один приём: если два приёма нашлись в одном предложении, остаётся более точный (первый).
// «Как нам решить вопрос с отсрочкой?» — вопрос «как?» Восса, а не ещё и вопрос об интересах; «Вы, наверное, думаете,
// что мы жадничаем» — анализ обвинений, а не ярлык. В разных предложениях засчитываются оба.
// «Пополам» по внешней мерке («середина между двумя индексами») — уже не механическое деление (Фишер, гл. 5): засчитываем мерку.
const SAME_SENTENCE: [BehaviorId, BehaviorId][] = [['calibrated', 'ask_interest'], ['accusation_audit', 'label'], ['criteria', 'split']]
const normQ = (s: string) => s.toLowerCase().replace(/ё/g, 'е').replace(/[^\p{L}\d]+/gu, ' ').trim()
function oneSentenceOne(hits: BehaviorHit[]): BehaviorHit[] {
  let out = hits
  for (const [keep, drop] of SAME_SENTENCE) {
    const k = out.find((h) => h.id === keep)
    const d = out.find((h) => h.id === drop)
    if (!k || !d) continue
    const a = normQ(k.quote), b = normQ(d.quote)
    if (a && b && (a.includes(b) || b.includes(a))) out = out.filter((h) => h !== d)
  }
  return out
}

function quoteAround(text: string, at: number, len: number): string {
  const before = text.slice(0, at)
  const start = Math.max(before.lastIndexOf('.'), before.lastIndexOf('!'), before.lastIndexOf('?'), before.lastIndexOf('\n')) + 1
  const rest = text.slice(at + len).search(/[.!?\n]/)
  const end = rest < 0 ? text.length : at + len + rest + 1
  const q = text.slice(start, end).trim()
  return q.length > 120 ? text.slice(Math.max(start, at - 40), Math.min(end, at + len + 40)).trim() + '…' : q
}

/**
 * Разметка реплики правилами — для офлайн-режима и как страховка к LLM.
 * Каждый индикатор не больше одного раза за ход, у каждого — цитата.
 */
export function detectBehaviors(text: string, ctx: MoveContext = {}): BehaviorHit[] {
  const hits = new Map<BehaviorId, BehaviorHit>()
  for (const b of BEHAVIORS) {
    const parts = METHOD_IDS.has(b.id) ? sentences(text) : [text]
    for (const [i, part] of parts.entries()) {
      if (!methodIntent(b.id, part, parts[i + 1])) continue
      for (const m of b.markers) {
        const found = m.exec(part)
        if (found) {
          // маркер «в начале предложения» захватывает точку прошлого: цитата — с самого предложения
          const lead = /^[.!?\n\s]*/u.exec(found[0])![0].length
          hits.set(b.id, { id: b.id, quote: quoteAround(part, found.index + lead, found[0].length - lead) })
          break
        }
      }
      if (hits.has(b.id)) break
    }
  }
  for (const [id, drop] of Object.entries(EXCLUDES) as [BehaviorId, BehaviorId[]][])
    if (hits.has(id)) for (const d of drop) hits.delete(d)

  if (ctx.offered && ctx.firstOffer && !hits.has('anchor')) hits.set('anchor', { id: 'anchor', quote: quoteAround(text, 0, 0) })
  const engaged = ENGAGES.some((id) => hits.has(id))
  if (ctx.offered && ctx.opponentJustOffered && !engaged && !hits.has('instant_counter'))
    hits.set('instant_counter', { id: 'instant_counter', quote: quoteAround(text, 0, 0) })
  if (engaged) hits.delete('instant_counter')
  return oneSentenceOne([...hits.values()])
}

const PRICE_REACTION = re("‹(?:загнул\\p{L}*|перебор|многовато|дорого|дороговато|круто берёшь|круто берете|жирно|не много ли|ну ты да[её]шь|ого|too (?:expensive|much|high)|pricey|steep|that's a lot|whoa|wow)›")

/**
 * Страховка поверх разметки нейросетью — там, где она путается:
 * размен засчитываем, только если в реплике есть обе стороны («если вы…, то мы…», «в обмен», «при условии»);
 * «последнее / финальное / это максимум» — ультиматум, даже если модель его не заметила;
 * реплика с ультиматумом или атакой не получает хороших приёмов, которые с ними несовместимы.
 */
export function guardBehaviors(text: string, hits: BehaviorHit[]): BehaviorHit[] {
  const rules = detectBehaviors(text)
  const byRule = (id: BehaviorId) => rules.find((h) => h.id === id)
  let out = hits.filter((h) => h.id !== 'package' || byRule('package'))
  // LLM может распознать новый оборот, но отрицание и риторический ответ проверяем по исходной фразе.
  const parts = sentences(text)
  out = out.filter((h) => !METHOD_IDS.has(h.id) || parts.some((p, i) =>
    h.quote && p.includes(h.quote) && methodIntent(h.id, p, parts[i + 1])))
  // «две тысячи — ты загнул» — реакция на цену, а не выпад и не похвала себе: без правила такую «атаку» модели не засчитываем
  out = out.filter((h) => !(h.id === 'attack' || h.id === 'irritator') || byRule(h.id) || !PRICE_REACTION.test(h.quote))
  for (const id of ['ultimatum', 'attack'] as const) {
    const pressure = byRule(id)
    if (pressure && !out.some((h) => h.id === id)) out = [...out, pressure]
  }
  const ids = new Set(out.map((h) => h.id))
  for (const [id, drop] of Object.entries(EXCLUDES) as [BehaviorId, BehaviorId[]][])
    if (ids.has(id)) out = out.filter((h) => !drop.includes(h.id as BehaviorId))
  return oneSentenceOne(out)
}

// ——— зеркало (Восс, гл. 2): ставится по последней реплике собеседника ———

const MIRROR_STOP = new Set([
  'это', 'вот', 'так', 'уже', 'ещё', 'еще', 'вас', 'вам', 'вами', 'тебя', 'тебе', 'тобой', 'нас', 'нам', 'меня', 'мне',
  'его', 'её', 'ее', 'они', 'она', 'оно', 'для', 'при', 'без', 'или', 'что', 'как', 'там', 'тут', 'только', 'прямо',
  'всё', 'все', 'весь', 'вся', 'даже', 'именно', 'самое', 'самый', 'the', 'you', 'your', 'and', 'but', 'for', 'with',
  'that', 'this', 'our', 'are', 'was', 'will', 'not', 'just', 'only', 'really',
])
const NUMBER_WORD = /^(?:ноль|один|одна|одно|два|две|три|четыре|пять|шесть|семь|восемь|девять|десять|\p{L}*надцать|двадцать|тридцать|сорок|пятьдесят|шестьдесят|семьдесят|восемьдесят|девяносто|сто|двести|триста|четыреста|\p{L}*сот|тысяч\p{L}*|полторы|пол|половин\p{L}*|one|two|three|four|five|six|seven|eight|nine|ten|twenty|thirty|forty|fifty|hundred|thousand|half)$/u
const MIRROR_LEAD = /^(?:(?:а|и|ну|так|то есть|в смысле|погодите|подождите|простите|извините|стоп|so|wait|sorry)[\s,!.…—-]+)*/iu
const MIRROR_NOT = /^(?:почему|зачем|как|какой|какая|какое|какие|каким|что|чего|чем|сколько|когда|где|куда|откуда|кто|чей|разве|неужели|ли|идёт|идет|договорились|согласны|согласен|да|нет|ок|окей|why|how|what|when|where|who|which|deal|ok|okay|yes|no)(?![\p{L}])/iu
const mWords = (s: string) => s.toLowerCase().replace(/ё/g, 'е').match(/[\p{L}\d-]+/gu) ?? []
/** Одно слово в другой форме: «предоплате» — «предоплата», «часа» — «часов». */
function sameWord(a: string, b: string): boolean {
  let p = 0
  while (p < a.length && p < b.length && a[p] === b[p]) p++
  return p >= 3 && p >= Math.min(5, Math.min(a.length, b.length) - 1)
}

/**
 * Зеркало: короткий вопрос (до шести слов), который повторяет ключевые слова последней реплики собеседника, —
 * без своих доводов, условий и вопросительных слов. «Только по предоплате?» после «Работаем только по предоплате».
 * Цифры не в счёт: «Двести?» — реакция на цену, а не зеркало.
 */
export function mirrorHit(text: string, said?: string): BehaviorHit | undefined {
  const t = text.trim()
  if (!said || !/\?[\s.…!]*$/u.test(t) || /\d|(?<![\p{L}])(?:если|if)(?![\p{L}])/iu.test(t)) return undefined
  const core = t.replace(MIRROR_LEAD, '')
  if (MIRROR_NOT.test(core)) return undefined
  const ws = mWords(core)
  if (!ws.length || ws.length > 6) return undefined
  const content = ws.filter((w) => w.length >= 3 && !MIRROR_STOP.has(w) && !NUMBER_WORD.test(w))
  if (!content.length) return undefined
  // последние две фразы собеседника: зеркало повторяет то, что только что прозвучало
  const tail = sentences(said).slice(-2).join(' ')
  const heard = mWords(tail)
  const hit = content.filter((w) => heard.some((h) => sameWord(w, h)))
  if (hit.length < Math.max(1, Math.ceil(content.length * 0.6))) return undefined
  return { id: 'mirror', quote: t.length > 90 ? `${t.slice(0, 88)}…` : t }
}

// ——— профиль против эталона ———

export const MINUTES_PER_TURN = 5

export interface ProfileRow {
  id: BehaviorId
  title: string
  polarity: Polarity
  count: number
  comparison?: { title: string; count: number } // отдельная агрегированная метрика; count приёма остаётся фактическим
  value?: number           // в единицах эталона
  benchmark?: Benchmark
  verdict?: 'skilled' | 'between' | 'average'
}

/** Частота запросов информации: объединение приёмов, максимум один вопросный ход за ход. */
export function questionFrequency(turns: { behaviors: BehaviorHit[]; talk?: string[] }[]) {
  const count = turns.filter((t) =>
    !t.behaviors.some((h) => h.id === 'attack' || h.id === 'ultimatum') &&
    (t.behaviors.some((h) => ['ask_interest', 'implication', 'need_payoff', 'mirror', 'calibrated'].includes(h.id) ||
      (['criteria', 'whatif'].includes(h.id) && h.quote.includes('?'))) || t.talk?.includes('question'))).length
  return { title: 'Вопросы-запросы информации (включая SPIN)', count }
}

/**
 * Профиль поведения игрока против эталона Rackham & Carlisle.
 * Честная оговорка: там считали высказывания в живой речи, у нас — письменные ходы, и один ход длиннее
 * одного высказывания. Поэтому доли у нас выходят выше, и эталон сильных — скорее нижняя планка, чем норма.
 */
export function behaviorProfile(turns: { behaviors: BehaviorHit[] }[]): ProfileRow[] {
  const n = turns.length
  const hours = (n * MINUTES_PER_TURN) / 60
  const questions = questionFrequency(turns)
  return BEHAVIORS.map((b) => {
    const count = turns.filter((t) => t.behaviors.some((h) => h.id === b.id)).length
    const row: ProfileRow = { id: b.id, title: b.title, polarity: b.polarity, count }
    if (b.id === 'ask_interest') row.comparison = questions
    const comparedCount = row.comparison?.count ?? count
    const bm = b.benchmark
    if (!bm || !n) return row
    row.benchmark = bm
    if (bm.unit === 'reasons') {
      // «доводов на аргумент» из счётчика не восстановить: индикатор и есть порог. Сработал — как у средних.
      row.verdict = count ? 'average' : 'skilled'
      return row
    }
    const v = (row.value = bm.unit === 'share' ? +((comparedCount / n) * 100).toFixed(1) : +(comparedCount / hours).toFixed(1))
    const higherIsBetter = b.polarity === 'strong'
    const nearSkilled = higherIsBetter ? v >= bm.skilled : v <= bm.skilled
    const nearAverage = higherIsBetter ? v <= bm.average : v >= bm.average
    row.verdict = nearSkilled ? 'skilled' : nearAverage ? 'average' : 'between'
    return row
  })
}

/** Сколько очков по осям набрал игрок: сильные в плюс, слабые в минус. Для «паутинки» в разборе. */
export function axisScores(turns: { behaviors: BehaviorHit[] }[]): Record<Axis, number> {
  const out: Record<Axis, number> = { create: 0, claim: 0, relate: 0, process: 0 }
  for (const t of turns)
    for (const h of t.behaviors) {
      const b = behaviorById(h.id)
      if (b) out[b.axis] += b.polarity === 'strong' ? 1 : b.polarity === 'weak' ? -1 : 0
    }
  return out
}

