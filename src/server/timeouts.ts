// Сколько сервер ждёт внешние сервисы, мс — в одном месте. Связка с браузером: звук реплики он ждёт 4 с
// (src/game/linePlayback.ts, LINE_WAIT_MS), поэтому ElevenLabs должен начать отвечать за elevenFirst — иначе сервер
// сам отдаёт SpeechKit (~0,5 с) и укладывается. Ход целиком браузер ждёт дольше: разметка + реплика + запасная модель.
// Часть переопределяется через .env; функции — чтобы читать .env после его загрузки.

const ms = (name: string, def: number) => () => Number(process.env[name] || def)
const fixed = (v: number) => () => v

export const WAIT = {
  /** потолок любого запроса к модели */
  llm: ms('LLM_TIMEOUT_MS', 25_000),
  /** разметка реплики игрока; не успела — ход размечают правила */
  analyze: fixed(8_000),
  /** основной разметчик, когда есть запасной (Claude → YandexGPT); не успел — размечает запасной в остаток analyze */
  analyzeFirst: ms('ANALYZE_TIMEOUT_MS', 4_000),
  /**
   * то же, когда быстрый разметчик (Pro) уже работает параллельно: его ответ готов, ждать Claude дольше незачем.
   * С прода 18.10: Sonnet — 2,2–2,3 с, но ~20% ходов дольше 4 с (сбои Vertex)
   */
  analyzeRace: ms('ANALYZE_RACE_TIMEOUT_MS', 3_000),
  /** заход (первые слова ответа, opener.ts): YandexGPT Pro с прода отвечает за 0,2–0,3 с; не успел — реплика без захода */
  opener: ms('OPENER_TIMEOUT_MS', 800),
  /** модель реплики, когда есть запасная; не успела — пишет запасная */
  voice: ms('VOICE_TIMEOUT_MS', 8_000),
  /** модель реплики без запасной */
  voiceAlone: fixed(12_000),
  /** нейросеть для омографов в озвучке; не успела — ударение по умолчанию */
  stress: ms('STRESS_LLM_MS', 500),
  /** SpeechKit: синтез */
  speechkit: fixed(10_000),
  /** SpeechKit: попытка распознавания; 10–15% запросов зависают (аудит C, 17.10) — после неё один повтор */
  stt: fixed(8_000),
  /** ElevenLabs: от запроса (с очередью) до первого байта; дольше — игрок слышит SpeechKit */
  elevenFirst: ms('ELEVEN_FIRST_BYTE_MS', 2_500),
  /** ElevenLabs целиком: новый голос в первый раз грузится 8–9 с, опоздавший звук ложится в кэш */
  eleven: ms('ELEVEN_TIMEOUT_MS', 15_000),
}
