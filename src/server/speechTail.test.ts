import { describe, expect, it } from 'vitest'
import { spokenTail } from './speech'

describe('остаток реплики после озвученного начала', () => {
  it('начало то же — говорим только остаток', () => {
    expect(spokenTail('Ладно, давай за двести. И убираешься ты.', 'Ладно, давай за двести.')).toBe('И убираешься ты.')
  })
  it('пометки, ударения, регистр и знаки поменялись — начало не повторяем', () => {
    expect(spokenTail('[sighs] Ладно, давай за двести. И убираешься ты.', '[Sighs] ладно давай за двести')).toBe('И убираешься ты.')
    expect(spokenTail('Ну ладно… Давай за д+евяносто, идёт?', 'Ну, ладно. Давай за девяносто')).toBe('идёт?')
    expect(spokenTail('Ещё бы. Посмотрим', 'Еще бы!')).toBe('Посмотрим')
  })
  it('реплику подрезали короче начала — добавлять нечего', () => {
    expect(spokenTail('Ладно, давай.', 'Ладно, давай за двести.')).toBe('')
  })
  it('переписан хвост начала — со следующей фразы, без повтора', () => {
    expect(spokenTail('Ладно, давай за двести пятьдесят. И убираешься ты.', 'Ладно, давай за триста.')).toBe('И убираешься ты.')
  })
  it('переписано всё — весь текст, как раньше', () => {
    expect(spokenTail('Нет. Так не пойдёт.', 'Ладно, давай за триста.')).toBe('Нет. Так не пойдёт.')
  })
})

describe('остаток реплики: уже сказанное не повторяется', () => {
  it('начало не совпало — озвучиваем только несказанные фразы, а не всю реплику заново', () => {
    const whole = 'Эй, друг, чего ты… Всё, я предупреждал. Разговор окончен, удачи вам с закупками.'
    // в итоговом тексте перед сказанным появилось новое начало — сказанное не совпадает с началом
    expect(spokenTail(`Ну всё. ${whole}`, 'Эй, друг, чего ты… Всё, я предупреждал.')).toBe('Ну всё. Разговор окончен, удачи вам с закупками.')
    // уже озвучен и сам остаток (второй проход после кусков) — больше ничего
    expect(spokenTail(`Ну всё. ${whole}`, `Эй, друг, чего ты… Всё, я предупреждал. Ну всё. Разговор окончен, удачи вам с закупками.`)).toBe('')
  })
})
