const VOWEL = 'аеёиоуыэюя'
const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** «Сем+ёрочка» ловим и как «Семерочка»: модель ё пишет не всегда. */
const pattern = (plain: string) => esc(plain).replace(/[её]/g, '[её]')

const FORMS = new Map<string, string>()
for (const [stem, ends] of STEMS) for (const e of ends) FORMS.set((stem + e).replace('+', '').toLowerCase().replace(/ё/g, 'е'), stem + e)
for (const w of WORDS) FORMS.set(w.replace('+', '').toLowerCase().replace(/ё/g, 'е'), w)

const ALL = new RegExp(
  `(?<![\\p{L}+])(${[...FORMS.keys()].sort((a, b) => b.length - a.length).map(pattern).join('|')})(?![\\p{L}])`,
  'giu',
)

/** Ставит ударения по словарю; где ударение уже стоит (от модели), не трогает. Регистр первой буквы — как в тексте. */
export function stress(text: string): string {
  return text.replace(ALL, (w: string) => {
    const marked = FORMS.get(w.toLowerCase().replace(/ё/g, 'е'))
    if (!marked) return w
    // буквы берём из текста, плюс — из словаря; «е» там, где в словаре «ё», — это «ё» (Семерочка → Семёрочка)
    const plain = marked.replace('+', '')
    const fixed = [...w].map((ch, i) => (plain[i] === 'ё' && ch === 'е' ? 'ё' : plain[i] === 'ё' && ch === 'Е' ? 'Ё' : ch)).join('')
    const at = marked.indexOf('+')
    return fixed.slice(0, at) + '+' + fixed.slice(at)
  })
}

/** Убирает ударения «+» перед гласными — для показа реплики на экране. */
export const unstress = (t: string) => t.replace(new RegExp(`\\+(?=[${VOWEL}])`, 'giu'), '')
