import { describe, expect, it } from 'vitest'
import { cardinal, ordinal, sayNumbers } from './numWords'

describe('числа словами для голоса', () => {
  it('количественные по падежам и родам', () => {
    expect(cardinal(2400)).toBe('две тысячи четыреста')
    expect(cardinal(2400, 'gen')).toBe('двух тысяч четырёхсот')
    expect(cardinal(2400, 'ins')).toBe('двумя тысячами четырьмястами')
    expect(cardinal(1200, 'acc')).toBe('тысячу двести')
    expect(cardinal(21000)).toBe('двадцать одна тысяча')
    expect(cardinal(1_500_000, 'gen')).toBe('миллиона пятисот тысяч')
    expect(cardinal(21, 'dat', 'f')).toBe('двадцати одной')
    expect(cardinal(0)).toBe('ноль')
  })

  it('порядковые: даты, годы, круглые', () => {
    expect(ordinal(25, 'nom', 'n')).toBe('двадцать пятое')
    expect(ordinal(3, 'gen', 'n')).toBe('третьего')
    expect(ordinal(2026, 'prep')).toBe('две тысячи двадцать шестом')
    expect(ordinal(2000)).toBe('двухтысячный')
    expect(ordinal(40)).toBe('сороковой')
  })

  it('реплика: падеж по предлогу, род по слову после числа, время, дроби; M12 не трогаем', () => {
    expect(sayNumbers('48 юаней за штуку, MOQ 2000 штук.')).toBe('сорок восемь юаней за штуку, MOQ две тысячи штук.')
    expect(sayNumbers('Адаптеры за 2400 юаней, держатели за 1200.')).toBe('Адаптеры за две тысячи четыреста юаней, держатели за тысячу двести.')
    expect(sayNumbers('до 40 дней, от 1500 штук, к 21 неделе, о 3 машинах, с 5 штуками')).toBe(
      'до сорока дней, от тысячи пятисот штук, к двадцати одной неделе, о трёх машинах, с пятью штуками')
    expect(sayNumbers('отгрузка 25 октября, к 5 ноября, в 2026 году, 2 года гарантии')).toBe(
      'отгрузка двадцать пятое октября, к пятому ноября, в две тысячи двадцать шестом году, два года гарантии')
    expect(sayNumbers('в 10:30 или 9:05, 1,5 недели, 2,5 процента, 3-й раз')).toBe(
      'в десять тридцать или девять ноль пять, полторы недели, две целых пять десятых процента, третий раз')
    expect(sayNumbers('датчики M12, 1 штука')).toBe('датчики M12, одна штука')
    // знак ударения перед числом не мешает найти предлог
    expect(sayNumbers('че́рез 14 дней')).toBe('че́рез четырнадцать дней')
  })
})
