// Осторожная эвристика: незавершённый хвост важнее точки от распознавателя.
const hanging = new Set(('и но а что чтобы потому если когда хотя либо или да зато же бы ли ведь вот ну типа короче значит э э-э эм м м-м в во на к ко с со у о об обо от до из за по под над при про для без через между перед после около').split(' '))
const numbers = /^(?:ноль|нуль|один|одна|одно|два|две|три|четыре|пять|шесть|семь|восемь|девять|десять|одиннадцать|двенадцать|тринадцать|четырнадцать|пятнадцать|шестнадцать|семнадцать|восемнадцать|девятнадцать|двадцать|тридцать|сорок|пятьдесят|шестьдесят|семьдесят|восемьдесят|девяносто|сто|двести|триста|четыреста|пятьсот|шестьсот|семьсот|восемьсот|девятьсот|тысяч[аи]?|миллион(?:а|ов)?|полтора|полторы|\d+(?:[.,]\d+)?)$/u
const unit = /(?:₽|%|руб(?:ль|ля|лей|ли|\.)?|р\.|процент(?:а|ов)?|доллар(?:а|ов)?|евро|дн(?:я|ей)|день|недел(?:ю|и|ь)|месяц(?:а|ев)?|год(?:а|ов)?|лет|час(?:а|ов)?|минут(?:а|ы|у)?|секунд(?:а|ы|у)?|тонн(?:а|ы|у)?|кг|килограмм(?:а|ов)?|штук(?:а|и|у)?|метр(?:а|ов)?)$/u

/** Сколько ждать, пока игрок договорит: настройка «коротко / средне / долго». */
export type PauseLevel = 'short' | 'medium' | 'long'
/** none — текста ещё нет (Яндекс, первые 2 с у Scribe); done — фраза закончена; unsure — непонятно; hang — оборвана на союзе. */
type Tail = 'none' | 'done' | 'unsure' | 'hang'

/**
 * Пороги тишины, мс. До 18.10 было 1000 / 550 / 1000 / 2000 (теперь это «коротко»): капитан — «отправляет слишком быстро,
 * человеку с медленными мыслями нужно успеть сформулировать». По умолчанию «средне».
 */
export const PAUSE_MS: Record<PauseLevel, Record<Tail, number>> = {
  short: { none: 1000, done: 600, unsure: 1000, hang: 2000 },
  medium: { none: 1500, done: 900, unsure: 1500, hang: 2600 },
  long: { none: 2300, done: 1400, unsure: 2300, hang: 3600 },
}

function tailOf(text: string): Tail {
  const raw = text.trim().toLowerCase().replaceAll('ё', 'е')
  if (!raw) return 'none'
  const bare = raw.replace(/[.!?…,:;]+$/u, '').trim()
  const words = bare.split(/\s+/u)
  const last = words.at(-1) ?? ''
  if (/[,;:…]$|\.{2,}$/u.test(raw) || hanging.has(last) || numbers.test(last)) return 'hang'
  if (/[.!?]$/u.test(raw) || /(?:^|\s)(?:по рукам|договорились|согласен|согласна|согласны)$/u.test(bare)) return 'done'
  if (unit.test(bare) && (words.slice(0, -1).some((w) => numbers.test(w)) || /\d(?:[.,]\d+)?(?:₽|%|кг)$/u.test(bare))) return 'done'
  // Несколько частых полных реплик без пунктуации.
  if (/^(?:вы согласны|вас устраивает|это окончательная цена|какая (?:цена|скидка)|сколько стоит|когда (?:доставка|оплата))$/u.test(bare)) return 'done'
  if (/^(?:я|мы|вы) (?:готов(?:ы|а)?|соглас(?:ен|на|ны)) .+\S$/u.test(bare) || /^(?:доставим|оплатим|подпишем|отгрузим|сделаем) (?:сегодня|завтра|вовремя)$/u.test(bare)) return 'done'
  return 'unsure'
}

export function endOfTurnMs(text = '', level: PauseLevel = 'medium'): number {
  return (PAUSE_MS[level] ?? PAUSE_MS.medium)[tailOf(text)]
}
