/**
 * Порядок показа вариантов: от худшего для игрока к лучшему (равные — как в деле).
 * Модель и движок по-прежнему работают с индексами из сценария — меняется только порядок на экране.
 */
export const worstFirst = (points: number[]) => points.map((_, k) => k).sort((a, b) => points[a] - points[b] || a - b)
