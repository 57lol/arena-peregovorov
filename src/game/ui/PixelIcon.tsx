export type IconName = keyof typeof ICONS

interface Props {
  name: IconName
  /** размер одного пикселя иконки в px экрана */
  px?: number
  color?: string
  color2?: string
  title?: string
  className?: string
}

export function PixelIcon({ name, px = 2, color = 'currentColor', color2, title, className }: Props) {
  const rows = ICONS[name]
  const w = rows[0].length
  const h = rows.length
  const rects: ReactElement[] = []
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x]
      if (ch === '.') continue
      rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={ch === '+' ? color2 ?? color : color} />)
    }
  })
  return (
    <svg
      className={className}
      width={w * px}
      height={h * px}
      viewBox={`0 0 ${w} ${h}`}
      shapeRendering="crispEdges"
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      {rects}
    </svg>
  )
}
