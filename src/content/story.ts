// Кампания «Новенький»: неделя в Алабуге. Семь дел по дням — от общаги до ночной смены.
// Бытовые дела учат по одному приёму, рабочие — дела из папки (их id не трогаем: на них ссылаются тренировки руководителя).
// Порядок — рекомендованный путь, но на карте открыто всё: игрок может начать с любой точки.

import type { SceneId } from '../game/ui/assets'

export type ChapterKind = 'life' | 'work' | 'finale'

export interface Chapter {
  /** id дела в папке (он же точка на карте) */
  id: string
  kind: ChapterKind
  day: string
  time: string
  place: string
  /** подпись метки на карте — два-три слова */
  label: string
  /** один приём, простыми словами — для карточки на карте */
  teaches: string
  /** 2–3 фразы перед брифом: где мы и что случилось */
  intro: string
  /** мостик к следующей главе: показывается на карте после первой партии */
  outro: string
  /** сколько минут идёт встреча по часам (у остановки — до автобуса); нет — час */
  minutes?: number
  /** комната встречи в 3D и сцена в классическом виде */
  room: SceneId
  /** массовка за столом (лица из src/game/ui/assets.ts); нет — обычные коллеги из пула */
  extras?: string[]
}

