function fill(text: string, sc: Scenario, report?: Report): string {
  const trap = report?.traps.find((t) => !t.avoided) ?? report?.traps[0]
  const compatible = sc.issues.find((i) => i.kind === 'compatible')
  const P = sc.player.profile
  const mine = [...sc.issues].sort((a, b) => issueWeight(P, b.id) - issueWeight(P, a.id))[0]
  const vars: Record<string, string> = {
    name: sc.opponent.character.name.split(/\s+/)[0],
    mine: mine?.title ?? '',
    trap: trap?.title ?? compatible?.title ?? '',
    both: trap?.bothWant ?? (compatible ? compatible.options[bestOption(P, compatible.id)] : ''),
    got: trap?.got ?? '',
  }
  return text.replace(/\{(\w+)\}/g, (m, k: string) => vars[k] ?? m)
}

function textsFor(sc: Scenario, female: boolean) {
  return LIBRARY[sc.id] ?? generic(female)
}

/** Все финалы дела — для карты. */
export function endingCatalog(sc: Scenario, female = false): EndingCard[] {
  const t = textsFor(sc, female)
  return ENDING_IDS.map((id) => ({ id, title: t[id].title, epilogue: fill(t[id].epilogue, sc), hint: HINT[id], tone: TONE[id] }))
}

/** Финал этой партии: название, эпилог с подстановкой пунктов, тон. */
export function endingOf(sc: Scenario, report: Report, state?: OpponentState, female = false): EndingCard {
  const id = pickEnding(endingFacts(sc, report, state))
  const t = textsFor(sc, female)[id]
  const raw = report.outcome.status !== 'deal' && t.noDeal ? t.noDeal : t.epilogue
  return { id, title: t.title, epilogue: fill(raw, sc, report), hint: HINT[id], tone: TONE[id] }
}
